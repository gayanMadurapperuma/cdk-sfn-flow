import * as iam from "aws-cdk-lib/aws-iam";
import * as sfn from "aws-cdk-lib/aws-stepfunctions";
import { Construct } from "constructs";

/**
 * The Step Functions workflow type.
 */
export enum WorkflowType {
  /** Long-running, exactly-once workflows (up to one year). */
  STANDARD = "STANDARD",
  /** High-volume, short-lived workflows (up to five minutes). */
  EXPRESS = "EXPRESS",
}

/**
 * Properties for a `FlowWorkflow`.
 */
export interface FlowWorkflowProps {
  /**
   * The workflow type.
   *
   * @default WorkflowType.STANDARD
   */
  readonly workflowType?: WorkflowType;

  /**
   * The state machine name.
   *
   * @default - a name is generated by CloudFormation
   */
  readonly name?: string;
}

/**
 * A Step Functions state machine generated from a behaviour-level config.
 */
export class FlowWorkflow extends Construct {
  /** The generated state machine. */
  public readonly stateMachine: sfn.StateMachine;

  /** The execution role of the state machine. */
  public readonly role: iam.IRole;

  constructor(scope: Construct, id: string, props: FlowWorkflowProps = {}) {
    super(scope, id);

    const definition = sfn.Pass.jsonata(this, "Start").next(
      sfn.Succeed.jsonata(this, "Done"),
    );

    this.stateMachine = new sfn.StateMachine(this, "StateMachine", {
      stateMachineName: props.name,
      stateMachineType: toStateMachineType(
        props.workflowType ?? WorkflowType.STANDARD,
      ),
      queryLanguage: sfn.QueryLanguage.JSONATA,
      definitionBody: sfn.DefinitionBody.fromChainable(definition),
    });
    this.role = this.stateMachine.role;
  }
}

function toStateMachineType(type: WorkflowType): sfn.StateMachineType {
  return type === WorkflowType.EXPRESS
    ? sfn.StateMachineType.EXPRESS
    : sfn.StateMachineType.STANDARD;
}
