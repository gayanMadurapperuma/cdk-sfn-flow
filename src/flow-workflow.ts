import { Annotations, Duration } from "aws-cdk-lib";
import * as iam from "aws-cdk-lib/aws-iam";
import * as logs from "aws-cdk-lib/aws-logs";
import * as sfn from "aws-cdk-lib/aws-stepfunctions";
import { Construct } from "constructs";
import { FlowResolver } from "./compiler/resolver";
import { validateWorkflow } from "./compiler/validator";
import { configureLogging, LoggingConfig } from "./observability";
import { Step } from "./steps/step";
import { DefaultsConfig, WorkflowType } from "./types";

/**
 * Properties for a `FlowWorkflow`.
 */
export interface FlowWorkflowProps {
  /** The steps, run in array order unless `next` says otherwise. */
  readonly steps: Step[];

  /**
   * The workflow type.
   *
   * @default WorkflowType.STANDARD
   */
  readonly workflowType?: WorkflowType;

  /**
   * The state machine name.
   *
   * @default - a name is generated by CloudFormation
   */
  readonly name?: string;

  /**
   * Maximum execution time.
   *
   * @default - no timeout (STANDARD: one year, EXPRESS: five minutes)
   */
  readonly timeout?: Duration;

  /**
   * Retry, catch and timeout defaults for `task`, `parallel`, `map` and `subflow` steps.
   *
   * @default - built-in retry, no catch, no timeout
   */
  readonly defaults?: DefaultsConfig;

  /**
   * Execution logging.
   *
   * @default - ERROR level, no execution data, 30-day retention
   */
  readonly logging?: LoggingConfig;

  /**
   * Enable X-Ray tracing.
   *
   * @default true
   */
  readonly tracing?: boolean;
}

/**
 * A Step Functions state machine generated from a behaviour-level config.
 */
export class FlowWorkflow extends Construct {
  /** The generated state machine. */
  public readonly stateMachine: sfn.StateMachine;

  /** The execution role of the state machine. */
  public readonly role: iam.IRole;

  /** The execution log group, unless logging is off. */
  public readonly logGroup?: logs.ILogGroup;

  /** The workflow type. */
  public readonly workflowType: WorkflowType;

  constructor(scope: Construct, id: string, props: FlowWorkflowProps) {
    super(scope, id);
    this.workflowType = props.workflowType ?? WorkflowType.STANDARD;
    const defaults = props.defaults ?? {};

    const resolver = new FlowResolver(new Construct(this, "States"), {
      workflowType: this.workflowType,
      defaults,
      topLevelCatches: defaults.catchErrors,
    });

    const result = validateWorkflow(props.steps ?? [], {
      context: resolver.context,
      topLevelCatchTargets: (defaults.catchErrors ?? []).map((c, i) => ({
        target: c.next,
        field: `defaults.catchErrors[${i}].next`,
      })),
    });
    if (result.errors.length > 0) {
      throw new Error(
        `FlowWorkflow '${this.node.path}' has ${result.errors.length} configuration error(s):\n` +
          result.errors.map((e) => `  - ${e}`).join("\n"),
      );
    }
    for (const warning of result.warnings) {
      Annotations.of(this).addWarningV2(
        `cdk-sfn-flow:${warning.rule}`,
        warning.message,
      );
    }

    const definition = resolver.build(props.steps);
    const logging = configureLogging(this, props.logging ?? {}, props.name);
    this.logGroup = logging.logGroup;

    this.stateMachine = new sfn.StateMachine(this, "StateMachine", {
      stateMachineName: props.name,
      stateMachineType:
        this.workflowType === WorkflowType.EXPRESS
          ? sfn.StateMachineType.EXPRESS
          : sfn.StateMachineType.STANDARD,
      queryLanguage: sfn.QueryLanguage.JSONATA,
      definitionBody: sfn.DefinitionBody.fromChainable(definition),
      timeout: props.timeout,
      tracingEnabled: props.tracing ?? true,
      logs: logging.logOptions,
    });
    this.role = this.stateMachine.role;
  }
}
