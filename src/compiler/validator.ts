import type { FlowWorkflowContext } from "./context";
import { isExpression } from "../jsonata";
import { StepEdge, StepValidator } from "../steps/builder";
import type { Step } from "../steps/step";
import { StepType } from "../steps/step-type";
import { END } from "../types";

/** A synth-time warning. */
export interface ValidationWarning {
  /** Stable rule id, used as the annotation id. */
  readonly rule: string;
  readonly message: string;
}

/** The result of validating a workflow. */
export interface ValidationResult {
  readonly errors: string[];
  readonly warnings: ValidationWarning[];
}

/** Options for `validateWorkflow`. */
export interface ValidateOptions {
  readonly context: FlowWorkflowContext;
  /** State names generated by the construct, which steps must not use. */
  readonly reservedIds?: string[];
  /** Extra catch edges applied to top-level resilient steps without their own catch. */
  readonly topLevelCatchTargets?: StepEdge[];
}

interface ScopeInfo {
  readonly path: string[];
  readonly steps: Step[];
  readonly top: boolean;
}

/**
 * Validates the step tree. Errors are collected (not thrown) so that all of them
 * can be reported at once; the caller throws.
 */
export function validateWorkflow(
  steps: Step[],
  options: ValidateOptions,
): ValidationResult {
  const errors: string[] = [];
  const warnings: ValidationWarning[] = [];
  const reserved = new Set([END, ...(options.reservedIds ?? [])]);

  const scopes = collectScopes(steps);

  // Ids are unique across the whole workflow, including nested steps.
  const seen = new Map<string, string>();
  for (const scope of scopes) {
    for (const step of scope.steps) {
      const path = format([...scope.path, step.id]);
      if (!step.id) {
        errors.push(
          `${format(scope.path) || "(workflow)"}: step ids must not be empty`,
        );
        continue;
      }
      if (reserved.has(step.id)) {
        errors.push(`${path}: '${step.id}' is a reserved step id`);
      }
      const previous = seen.get(step.id);
      if (previous !== undefined) {
        errors.push(
          `${path}: duplicate step id '${step.id}' (also used at ${previous})`,
        );
      } else {
        seen.set(step.id, path);
      }
    }
  }

  const topIds = new Set(steps.map((s) => s.id));
  for (const edge of options.topLevelCatchTargets ?? []) {
    if (!topIds.has(edge.target)) {
      errors.push(
        `(workflow): '${edge.field}' target '${edge.target}' must be a top-level step id`,
      );
    }
  }

  for (const scope of scopes) {
    validateScope(scope, options, seen, errors, warnings);
  }

  return { errors, warnings };
}

function validateScope(
  scope: ScopeInfo,
  options: ValidateOptions,
  allIds: Map<string, string>,
  errors: string[],
  warnings: ValidationWarning[],
): void {
  const scopePath = format(scope.path) || "(workflow)";
  if (scope.steps.length === 0) {
    errors.push(`${scopePath}: steps must not be empty`);
    return;
  }

  const ids = new Set(scope.steps.map((s) => s.id));
  const graph = new Map<string, Set<string>>();

  scope.steps.forEach((step, index) => {
    const path = format([...scope.path, step.id]);
    const builder = step._builder;
    const v: StepValidator = {
      path,
      context: options.context,
      error: (message) => errors.push(`${path}: ${message}`),
      warn: (rule, message) =>
        warnings.push({ rule, message: `${path}: ${message}` }),
      expression: (field, value) => {
        if (value !== undefined && !isExpression(value)) {
          warnings.push({
            rule: "JsonataNotWrapped",
            message: `${path}: '${field}' is not wrapped in {% %} and is treated as a literal string`,
          });
        }
      },
    };
    builder.validate(v);

    const targets = new Set<string>();
    for (const edge of builder.edges()) {
      if (edge.target === END) {
        if (edge.field !== "next") {
          errors.push(
            `${path}: '${edge.field}' cannot be '${END}'; route to a Step.succeed or Step.fail instead`,
          );
        }
        continue;
      }
      if (!ids.has(edge.target)) {
        const elsewhere = allIds.get(edge.target);
        errors.push(
          elsewhere === undefined
            ? `${path}: '${edge.field}' target '${edge.target}' does not exist`
            : `${path}: '${edge.field}' target '${edge.target}' is in a different scope (${elsewhere}); targets must be in the same step list`,
        );
        continue;
      }
      targets.add(edge.target);
    }
    // Default catches are validated once in validateWorkflow; here they only add graph edges.
    if (
      scope.top &&
      builder.resilience &&
      builder.resilience.catchErrors === undefined
    ) {
      for (const edge of options.topLevelCatchTargets ?? []) {
        if (ids.has(edge.target)) targets.add(edge.target);
      }
    }
    if (
      !builder.terminal &&
      builder.next === undefined &&
      index + 1 < scope.steps.length
    ) {
      targets.add(scope.steps[index + 1].id);
    }
    graph.set(step.id, targets);
  });

  // Reachability from the first step.
  const reachable = new Set<string>();
  const queue = [scope.steps[0].id];
  while (queue.length > 0) {
    const id = queue.shift()!;
    if (reachable.has(id)) continue;
    reachable.add(id);
    queue.push(...(graph.get(id) ?? []));
  }
  for (const step of scope.steps) {
    if (!reachable.has(step.id)) {
      warnings.push({
        rule: "UnreachableStep",
        message: `${format([...scope.path, step.id])}: step is unreachable and will not be part of the state machine`,
      });
    }
  }

  // Loops through a choice must contain a wait.
  const types = new Map(scope.steps.map((s) => [s.id, s.type]));
  for (const component of stronglyConnected(graph)) {
    const isCycle =
      component.length > 1 || graph.get(component[0])?.has(component[0]);
    if (!isCycle) continue;
    const kinds = component.map((id) => types.get(id));
    if (kinds.includes(StepType.CHOICE) && !kinds.includes(StepType.WAIT)) {
      warnings.push({
        rule: "ChoiceLoopWithoutWait",
        message: `${scopePath}: loop ${component.join(" -> ")} has no wait step and can spin through state transitions`,
      });
    }
  }
}

/** All step lists in the tree, depth first, with their paths. */
function collectScopes(steps: Step[]): ScopeInfo[] {
  const scopes: ScopeInfo[] = [];
  const visit = (list: Step[], path: string[], top: boolean) => {
    scopes.push({ path, steps: list, top });
    for (const step of list) {
      for (const child of step._builder.children()) {
        visit(
          child.steps,
          child.name ? [...path, step.id, child.name] : [...path, step.id],
          false,
        );
      }
    }
  };
  visit(steps, [], true);
  return scopes;
}

function format(path: string[]): string {
  return path.join(" > ");
}

/** Tarjan's strongly connected components. */
function stronglyConnected(graph: Map<string, Set<string>>): string[][] {
  let index = 0;
  const indices = new Map<string, number>();
  const low = new Map<string, number>();
  const stack: string[] = [];
  const onStack = new Set<string>();
  const result: string[][] = [];

  const connect = (node: string) => {
    indices.set(node, index);
    low.set(node, index);
    index++;
    stack.push(node);
    onStack.add(node);
    for (const next of graph.get(node) ?? []) {
      if (!indices.has(next)) {
        connect(next);
        low.set(node, Math.min(low.get(node)!, low.get(next)!));
      } else if (onStack.has(next)) {
        low.set(node, Math.min(low.get(node)!, indices.get(next)!));
      }
    }
    if (low.get(node) === indices.get(node)) {
      const component: string[] = [];
      let member: string;
      do {
        member = stack.pop()!;
        onStack.delete(member);
        component.push(member);
      } while (member !== node);
      result.push(component.reverse());
    }
  };

  for (const node of graph.keys()) {
    if (!indices.has(node)) connect(node);
  }
  return result;
}
